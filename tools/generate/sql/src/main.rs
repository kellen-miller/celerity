use std::{
    env, fs,
    path::{Path, PathBuf},
    process::{Command, ExitCode},
};

use regex::Regex;

type GenerationResult<T> = Result<T, Box<dyn std::error::Error>>;

const SQLC_VERSION: &str = "v1.31.1";
const GENERATOR_VERSION: &str = "//! sqlc-gen-rust version: v0.1.12";
const OUTPUTS: [&str; 3] = ["home/mod.rs", "home/legacy.rs", "sync/mod.rs"];

fn main() -> ExitCode {
    match generate() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("SQL generation failed: {error}");
            ExitCode::FAILURE
        }
    }
}

fn generate() -> GenerationResult<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .and_then(Path::parent)
        .ok_or("sql-codegen must live under tools/generate/")?;
    let output_root = match env::args_os().skip(1).collect::<Vec<_>>().as_slice() {
        [] => root.to_path_buf(),
        [flag, path] if flag == "--output-root" => PathBuf::from(path),
        _ => return Err("usage: sql-codegen [--output-root PATH]".into()),
    };
    let version = Command::new("sqlc").arg("version").output()?;
    if !version.status.success() || String::from_utf8(version.stdout)?.trim() != SQLC_VERSION {
        return Err(format!("sqlc {SQLC_VERSION} is required").into());
    }

    // Generate in a temporary project so drift checks never mutate the checkout.
    // The same authoritative schema files initialize the production databases.
    let temporary = tempfile::tempdir()?;
    fs::copy(
        root.join("tools/generate/sqlc.yaml"),
        temporary.path().join("sqlc.yaml"),
    )?;
    copy_sources(&root.join("sql"), &temporary.path().join("sql"))?;

    let status = Command::new("sqlc")
        .args(["generate", "-f"])
        .arg(temporary.path().join("sqlc.yaml"))
        .current_dir(temporary.path())
        .status()?;
    if !status.success() {
        return Err(format!("sqlc generation exited with {status}").into());
    }

    {
        let generated = Path::new("gen/rust/sql/src");
        for output in OUTPUTS {
            let path = output_root.join(generated).join(output);
            fs::create_dir_all(path.parent().ok_or("missing output parent")?)?;
            let source = fs::read_to_string(temporary.path().join(generated).join(output))?;
            fs::write(&path, normalize(&source)?)?;
            let status = Command::new("rustfmt")
                .args(["--edition", "2024"])
                .arg(&path)
                .status()?;
            if !status.success() {
                return Err(format!("rustfmt failed for {}", path.display()).into());
            }
        }
    }

    Ok(())
}

fn copy_sources(source: &Path, destination: &Path) -> GenerationResult<()> {
    fs::create_dir_all(destination)?;
    for entry in fs::read_dir(source)? {
        let entry = entry?;
        if entry.file_type()?.is_dir() {
            copy_sources(&entry.path(), &destination.join(entry.file_name()))?;
        } else {
            fs::copy(entry.path(), destination.join(entry.file_name()))?;
        }
    }

    Ok(())
}

fn normalize(source: &str) -> GenerationResult<String> {
    if !source.starts_with("//! Code generated by sqlc-gen-rust. SHOULD NOT EDIT.\n")
        || !source.lines().any(|line| line == GENERATOR_VERSION)
        || !source
            .lines()
            .any(|line| line == format!("//! sqlc version: {SQLC_VERSION}"))
    {
        return Err("unexpected sqlc generator format/version".into());
    }

    // Normalize pinned upstream generation defects, never SQL or bindings.
    // Keep this small until the upstream generator emits lint-clean code.
    let empty_rows = Regex::new(
        r"pub struct (\w+Row) \{\}\nimpl (\w+Row) \{\n    pub fn from_row\(row: &rusqlite::Row\) -> rusqlite::Result<Self> \{\n        Ok\(Self \{\}\)\n    \}\n\}\n",
    )?;
    let mut output = empty_rows
        .replace_all(source, "")
        .into_owned()
        .replace(
            "rusqlite::Connection::prepare(&self, sql)",
            "rusqlite::Connection::prepare(self, sql)",
        )
        .replace(
            "    pub fn as_params(&self) -> impl rusqlite::Params {\n        ()\n    }",
            "    pub fn as_params(&self) -> impl rusqlite::Params {}",
        );
    let fallible =
        Regex::new(r"(?m)^(    )((?:pub )?fn [^{;]+?-> rusqlite::Result[^\n]*(?:\{|;))")?;
    output = fallible.replace_all(&output, "$1/// Execute or prepare the generated SQLite operation.\n$1///\n$1/// # Errors\n$1/// Returns SQLite preparation, execution, or row decoding errors.\n$1$2").into_owned();
    let mut normalized = String::new();
    let mut lines = output.lines().peekable();
    while let Some(line) = lines.next() {
        normalized.push_str(line);
        normalized.push('\n');
        if line.trim() == "}" && lines.peek().is_some_and(|next| !next.trim().is_empty()) {
            normalized.push('\n');
        }
    }

    Ok(normalized)
}
